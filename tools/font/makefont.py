W, H, PER_ROW = 8, 8, 15
chars = [chr(c) for c in range(ord(" "), ord("~") + 1)]
missing = [c for c in chars if c not in G]
assert not missing, f"missing glyphs: {missing}"
rows = (len(chars) + PER_ROW - 1) // PER_ROW
pixels = [[(0, 0, 0, 0)] * (PER_ROW * W) for _ in range(rows * H)]
for i, c in enumerate(chars):
    start, glyph = G[c]
    assert start + len(glyph) <= H, f"{c!r} is too tall"
    gx, gy = (i % PER_ROW) * W, (i // PER_ROW) * H
    for y, line in enumerate(glyph):
        assert len(line) <= W - 1, f"{c!r} is too wide"
        for x, ch in enumerate(line):
            if ch == "#":
                pixels[gy + start + y][gx + x] = (255, 255, 255, 255)

raw = b"".join(b"\x00" + bytes(v for p in row for v in p) for row in pixels)


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", PER_ROW * W, rows * H, 8, 6, 0, 0, 0))
png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_bytes(png)
